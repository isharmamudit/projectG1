const SEHAT_STRINGS: Record<string, SehatCopy> = { en, hi, te, bn, mr }

/**
 * Falls back to English for the seven other site languages rather than
 * rendering blanks. The caller still sends the user's real language code to
 * the API, so the AI's own words come back in their language regardless.
 */
export function sehatT(lang: string): SehatCopy {
  return SEHAT_STRINGS[lang] ?? en
}

/** True when this file actually has UI chrome for the given site language. */
export function hasSehatCopy(lang: string): boolean {
  return lang in SEHAT_STRINGS
}
